import { Router } from 'express';
import { authenticate } from '../../middleware/authenticate.js';
import { authorize } from '../../middleware/authorize.js';
import { validate } from '../../middleware/validate.js';
import { idempotency } from '../../middleware/idempotency.js';
import * as v from './bookings.schema.js';
import * as c from './bookings.controller.js';
const router = Router();
const managers = authorize('SUPER_ADMIN', 'ADMIN', 'ACCOUNTANT', 'STAFF');
router.use(authenticate, managers);
router.get('/', validate(v.listQuery, 'query'), c.list);
router.get('/collections', validate(v.listQuery, 'query'), c.collections);
router.post('/', managers, idempotency, validate(v.createSchema), c.create);
router.get('/:id', c.get);
router.put('/:id', managers, validate(v.updateSchema), c.update);
router.patch('/:id/status', managers, validate(v.statusSchema), c.status);
router.post('/:id/payments', idempotency, validate(v.paymentSchema), c.payment);
router.post('/:id/refunds', managers, idempotency, validate(v.refundSchema), c.refund);
router.post('/:id/cancel', managers, idempotency, validate(v.cancelSchema), c.cancel);
router.get('/:id/ledger', c.ledger);
router.get('/:id/pos-handoff', c.handoff);
export default router;
